<p>О преимуществах Windows 7 &nbsp;уже было сказано и написано множество слов, а потому перейдем сразу к делу. Итак, вы решили установить эту ОС на свой Mac. Установка Windows 7 на Mac требует определенной подготовки устройства к самому процессу, ну и, конечно же, определенный запас времени (в лучшем случае вся процедура занимает около часа).</p>

<h2>Как подготовиться к установке винды на Mac?</h2>

<p>Установка Windows 7 на Mac, как мы уже сказали – процесс специфичный. Для того, чтобы он прошел успешно и вы ничего не испортили, следует выполнить четыре несложных пункта.</p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="обновление системы" src="/upload/image/exit.png" style="float:left; height:30px; width:30px" title="обновление системы" /></span></span>&nbsp;Нужно обновить систему (сделать это можно, выбрав «Обновление программ…» в Apple).</p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="диск" src="/upload/image/cd_jewel_case_icon_(1).png" style="float:left; height:30px; width:30px" title="диск" /></span></span>&nbsp;Найти DVD с записанной <a href="http://www.ansee.ru/ustanovka-windows-7.php">Windows 7</a>, а также родной DVD-диск с Mac OS.</p>

<p>На жестком диске должно быть минимум 10 Гб свободного места.</p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="бекап" src="/upload/image/burn.png" style="float:left; height:30px; width:30px" title="бекап" /></span></span>&nbsp;Профессионалы рекомендуют также сделать бэкап своей системы, используя Time Machine (это нужно для того, чтобы не утратить важных файлов во время изменения разметки диска).</p>

<h3>Как происходит установка</h3>

<div class="spoiler-body">
<p style="text-align:left"><a href="http://www.ansee.ru/ustanovka-windows.php">Установка Windows</a> 7 на Mac только на последних этапах ничем не отличается от стандартной переустановки Windows. Сперва же придется «поиграться» с родными программами устройства.<span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="Установка Windows 7 на Mac" src="/upload/image/maclogo.png" style="float:right; height:191px; margin-bottom:5px; margin-left:5px; margin-right:5px; margin-top:5px; width:180px" title="Установка Windows 7 на Mac" /></span></span></p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="установка windows на mac os" src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="установка windows на mac os" /></span></span>Нужно закрыть все, без исключения (в том числе и фоновые) программы.</p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="иконка " src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="иконка " /></span></span>Затем требуется открыть Finder и Boot Camp (находится в разделе «Служебные программы»).</p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="иконка " src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="иконка " /></span></span>Жмем кнопку «Продолжить» (на этом этапе Windows 7 в списке не будет – это нормально).</p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="иконка " src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="иконка " /></span></span>Далее система попросит определить объем жесткого диска под Windows 7. Минимальный составляет 5 Гб, однако лучше выбрать оставить около 20 (для более стабильной работы системы и возможности устанавливать программы Windows). Указываем нужный нам объем и нажимаем «Разбить на разделы».</p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="иконка " src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="иконка " /></span></span>По завершении процесса разметки на рабочем столе оказывается новый диск на 20 Гб (по умолчанию он называется BOOTCAMP).</p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="иконка " src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="иконка " /></span></span>Вставляем DVD с Windows и начинаем установку Windows 7 на Mac.</p>

<p style="text-align:left"><span style="font-size:18px"><span style="font-family:times new roman,times,serif"><img alt="иконка " src="/upload/image/new_go_next.png" style="float:left; height:30px; width:30px" title="иконка " /></span></span>Выбираем для установки раздел с пометкой BOOTCAMP) и нажимаем «Форматировать».</p>

<p>Дальше&nbsp; начинается весьма скучная и тривиальная процедура установки Windows 7 на Mac. Когда она закончится, диск нужно вытащить и компьютер будет перезагружен. Стоит установить все обновления (в их числе будут важные драйвера, которые позволят улучшить качество изображения и не только).</p>

<p>С аудиодрайвером проблему таким образом не решить, а потому придется воспользоваться родным диском Мака и уже знакомым нам Boot Camp. Когда вы установите драйвер – система готова к использованию.</p>
