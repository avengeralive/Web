<p style="text-align:justify"><span style="font-size:18px"><em><span style="font-family:times new roman,times,serif"><img alt="сбор данных" src="/upload/image/database.png" style="float:left; height:30px; width:30px" title="сбор данных" /></span></em><span style="font-family:times new roman,times,serif">сбор и централизованное хранение всей важной информации компании;</span></span></p>

