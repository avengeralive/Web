<p class='blog_title'>Компьютер сам перезагружается</p>
<p class='blog_date'>Автор: administrator</p>
<p class='blog_date1'>Дата: 2013-01-10</p>
<p class='blog_text'><h1 style="text-align:center"><strong><em>Компьютер сам перезагружается<img alt="Компьютер сам перезагружается" src="/upload/image/windows.jpg" style="height:381px; margin-bottom:5px; margin-left:5px; margin-right:5px; margin-top:5px; width:507px" title="Компьютер сам перезагружается" /></em></strong></h1>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Итак, ваш компьютер&nbsp;сам перезагружается, и вы не знаете что делать? Для начала необходимо выяснить причину этого. А только потом пытаться решить её. Причины перезагрузки могут быть разными – программного и аппаратного уровня.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Давайте рассмотрим самые основные из них, которые наиболее часто встречаются.</span></span></p>

<h2 style="text-align:center"><strong><span style="color:#173469"><em><span style="font-size:22px"><span style="font-family:times new roman,times,serif">Компьютер сам перезагружается - перегрев!</span></span></em></span></strong></h2>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Зачастую, причиной перезагрузок является сильный перегрев каких-нибудь деталей. В основном – процессора или видеокарты. Это чревато тем, что деталь может выйти из строя. Ремонт может оказаться очень дорогим и нерентабельным.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Причин, когда компьютер сам перезагружается&nbsp;много. Либо вы слишком сильно нагружаете свой компьютер (ноутбук) или же у вас очень слабая система охлаждения. Если раньше такого не было, то возможно ваши кулеры вышли из строя или их нужно просто смазать. Возможно, нужно будет их заменить.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Производить замену нужно аккуратно, не задев других деталей. Поскольку можно испортить что-то еще. Смазывать нужно ось изнутри. Нужно будет отклеить наклейку и залить машинного масла. Затем вернуть наклейку обратно.</span></span></p>

<h3 style="text-align:center"><strong><span style="color:#173469"><span style="font-size:22px"><em><span style="font-family:times new roman,times,serif">Если вообще не загружается и постоянно перезагружается</span></em></span></span></strong></h3>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Иногда бывает так, что компьютер никак не может загрузиться и постоянно перезапускается. Это означает то, что у вашего компьютера есть какие-то проблемы, которые не дают загрузиться.</span></span></p>

<p style="text-align:center"><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Что делать в этом случае, когда компьютер сам перезагружается? </span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">В этих случаях нужно до попытки загрузиться нажать F8. Там внизу будет надпись – отключить автоматическую перезагрузку. В результате этого перезагружаться не будет, но система не запуститься всё равно. Зато вы увидите сообщение об ошибке. Вам будет указана реальная проблема, из-за которой загрузиться система не может.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">После того, как узнаете реальную проблему, нужно будет её устранить. Вариантов проблем довольно много.</span></span></p>

<h4 style="text-align:center"><strong><span style="color:#173469"><em><span style="font-size:22px"><span style="font-family:times new roman,times,serif">Компьютер сам перезагружается, возможно и вирусы...</span></span></em></span></strong></h4>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Проблема перезагрузки компьютера так же часто кроется в вирусах. Обычно, такое происходит на тех компьютерах, на которых установлен плохой антивирус или старая антивирусная база.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">В этом случае нужно очистить компьютер от вирусов и установить хороший антивирус с новой базой. Но как сделать это, если компьютер перезагружается и не дает ничего сделать? Разумеется, вы можете сами полностью форматировать свой жесткий диск и затем установить всё заново. А надо ли это?</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Как один из вариантов, это подключить ваш жесткий диск к другому компьютеру и там уже всё почистить.</span></span></p>

<h5 style="text-align:center"><span style="color:#173469"><strong><em><span style="font-size:22px"><span style="font-family:times new roman,times,serif">Неисправности в аппаратной части компьютера</span></span></em></strong></span></h5>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Кроме этого проблемы компьютера, который сам перезагружается, могут быть различные проблемы с деталями. Например, где-то отошел шлейф, или отошел контролёр жесткого диска. Другими словами, вариантов проблем может быть много.</span></span></p>

<p><span style="font-size:20px"><em><span style="font-family:times new roman,times,serif">Проблемы с питанием</span></em></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Так же стоит отметить такой момент, как нехватка напряжения. Если вашему компьютеру не хватает питания, то он будет перезагружаться. Это может быть в двух случаях:</span></span></p>

<ul>
	<li><span style="font-size:18px"><span style="font-family:times new roman,times,serif">У вас слабый блок питания;</span></span></li>
	<li><span style="font-size:18px"><span style="font-family:times new roman,times,serif">В электрической сети нехватка напряжения.</span></span></li>
</ul>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Если проблема с блоком питания, то значит нужно заменить его на новый, более мощный. Делать это нужно очень аккуратно. Поскольку вы можете что-то подключить не так, и в итоге какая-нибудь деталь может сгореть.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Если проблема с электрической сетью, то возможно кто-то из соседей варит или проблема на электростанции. Просто немного подождите.</span></span></p>

<p><span style="font-size:20px"><span style="font-family:times new roman,times,serif">Вывод!</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Как видите, проблем может быть довольно много. Выше описаны самые основные.&nbsp; </span></span></p>

