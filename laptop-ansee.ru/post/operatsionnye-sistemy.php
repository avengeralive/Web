<p class='blog_text'><h1 style="text-align:center"><span style="font-size:24px"><span style="font-family:times new roman,times,serif"><strong><em>Современные операционные системы</em></strong></span></span></h1>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Постоянно работая за компьютером, большинство пользователей и не догадываются, что одним нажатием кнопки они заставляют активироваться огромное количество микропроцессов. Обычный человек не особо задумывается об операционной системе, разве только тогда, когда выбирает какую бы себе поставить, чтобы и компьютер быстрее работал, и приятней пользоваться было.</span></span></p>

<h2 style="text-align:center"><strong><em><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469">Так что собой представляет операционная система (ОС)?</span></span></span></em></strong></h2>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Используя простой язык можно сказать, что это набор системных программ, которые предназначены для облегчения взаимодействия человека с компьютером и выполнения всех иных программ. Чтобы иметь общее представления о ОС, этого хватит. А желающих углубить знания можно отослать к учебникам.</span></span></p>

<p>К<span style="font-size:18px"><span style="font-family:times new roman,times,serif">акие бывают операционные системы?Обычный пользователь на этот вопрос громогласно ответит: «Windows есть! Эмм.… Ещё там MacOS и UNIX-подобные, да?».</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">С точки зрения профессионала этот ответ неверный. Всё намного шире и порядком сложнее, но обычному пользователю знать и больше не нужно, потому, и так сойдёт.</span></span></p>

<blockquote>
<p><em><span style="font-size:20px"><span style="font-family:georgia,serif">По статистике лидером по использованию является Windows, следует ей MacOs, а недооценённый Unix тянется в хвосте.</span></span></em></p>
</blockquote>

<h3 style="text-align:center"><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469"><strong>Windows</strong></span></span></span></h3>

<p style="text-align:center"><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469"><strong><img alt="windows" src="/upload/image/windows_(1).jpg" style="border-bottom-style:solid; border-bottom-width:1px; border-left-style:solid; border-left-width:1px; border-right-style:solid; border-right-width:1px; border-top-style:solid; border-top-width:1px; float:left; height:207px; margin-bottom:5px; margin-left:5px; margin-right:5px; margin-top:5px; width:220px" title="windows" /></strong></span></span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Выпускает её гигант на рынке компьютерных технологий Microsoft. Данная ОС подходит тем, кому нужна легкость в освоении и простота. Не нужно особо напрягаться, все настройки выполняются в удобном оконном режиме, знания консольных команд для ведения диалога с компьютером не обязательны.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Так же большим плюсом является популярность этой операционной системы. У пользователя не возникнет проблемы с поиском какой-то нужной программы, в интернете можно найти приложения на все случаи жизни. Это же касается и игр.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Основным минусом являются вирусы. Их огромное количество и разнообразие. Странствуя по интернету, хотя бы раз в день вы попадает на сайт, который упорно хочет вас «заразить». Антивирусы не дают 100% шанса защиты, да и с ключами активации бывает много проблем.</span></span></p>

<h3 style="text-align:center"><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469"><strong>Unix</strong><strong>-системы</strong></span></span></span></h3>

<p style="text-align:center"><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469"><strong><img alt="линукс" src="/upload/image/linux.jpg" style="float:left; height:165px; margin-bottom:5px; margin-left:5px; margin-right:5px; margin-top:5px; width:220px" title="линукс" /></strong></span></span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">В этой ОС есть пару моментов отпугивающих обычных людей. О ней ходит репутация, как о системе для профессионалов, поезженных на компьютерных технологиях. Этот стереотип появился не просто так, да, для овладения данной ОС нужны базовые знания, потому, что интерфейс не очень дружелюбен. Возьмём, например, Linux – система создана программистами для своих нужд. Их, прежде всего, интересует удобство разработки, защита и быстродействие.&nbsp; Потому и понятно, что не очень легко разобраться человеку без определённых знаний, но, удобство растёт с каждым годом – создано много дистрибутивов, которые всё упростят до уровня Windows.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Так же большим плюсом является малое количество написанных вирусов, а вирусы под Windows не могут навредить данной системе. Просторы интернета становится безопасными!</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Заядлый геймер никогда не установит Linux – нету качественных и интересных игр, а с помощью эмулятора сильно не поиграешь. Это является большим минусом, так как система создана не для игр, а ради разработки.</span></span></p>

<h3 style="text-align:center"><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469"><strong>MacOS</strong></span></span></span></h3>

<p style="text-align:center"><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><span style="color:#173469"><strong><img alt="мак" src="/upload/image/mac_os.jpg" style="float:left; height:165px; margin-bottom:5px; margin-left:5px; margin-right:5px; margin-top:5px; width:220px" title="мак" /></strong></span></span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Эта система является эталоном простоты и удобства, а главное – красоты. Внешний вид на очень высоком уровне, иногда приятно просто посмотреть, и насладится тщательной продуманностью дизайна. Эта ОС выпускается под продукцию Apple, потому в России является редкой и дорогостоящей вещью для элиты.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Как и в случае с Linux, написано малое количество вирусов. Игр не так много как на Windows, но все же найдется во что поиграть.</span></span></p>

<p> </p>

<p><span style="color:#173469"><em><span style="font-size:22px"><span style="font-family:times new roman,times,serif"><strong>Итог:</strong></span></span></em></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Если хочется пользоваться функциональной, простой и быстрой ОС, и вам не жалко денег на это – пользуйтесь MacOS на здоровье!</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Интересует программирование? Так почему вы ещё это читаете? Скачивайте Linux и бегом за работу.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Если поиграть в игры хочется или там с документами разобраться, а с компьютерными сложностями разбираться нет желания, да и денег жалко – то Windows для вас.&nbsp;</span></span></p>
