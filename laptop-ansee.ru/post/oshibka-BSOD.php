<p class='blog_title'>Ошибка BSOD – «черная метка» или нелепая случайность?</p>
<p class='blog_date'>Автор: </p>
<p class='blog_date1'>Дата: 2014-07-14</p>
<p class='blog_text'><h1>Ошибка BSOD – «черная метка» или нелепая случайность?</h1>

<p>Представьте, что вы играете в любимую игру или же дописываете реферат/программный код для очень важной работы…и тут возникает пресловутый «синий экран смерти». Возможно, он появляется для вас в первый раз – и вы видите абсолютно синий экран, на котором написано по-английски что-то вроде «Была обнаружена проблема…» с кучей непонятных обозначений. Что делать? Правильно, вы в панике, пытаетесь перезагрузить компьютер, но дальше появляются следующие варианты развития ситуации – либо во время загрузки системы на долю секунды появляется знакомый синий экран, или же во время пользования компьютером вы вновь получаете тот самый “Blue Screen of Death”, иначе называемый ошибкой BSOD. Что это такое? Это сообщение о критическом сбое операционной системы, при котором дальнейшее функционирование попросту невозможно. Также на этом экране указывается служба/драйвер, вызвавшие BSOD Windows – иногда указывается конкретный драйвер или DLL-библиотека, вызвавшая критичный сбой, но чаще всего ошибки обозначаются специальными кодами.</p>

<p style="text-align: center;"><img alt="ошибки bsod" src="/img/BSOD-0xA-screen-shot.jpg" style="margin-left: 5px; margin-right: 5px; width: 625px; height: 385px;" title="ошибки bsod" /></p>

<h2>Ошибки BSOD… это значит, что ПК в опасности?</h2>

<p>Честно говоря – да, ведь ошибки BSOD возникают от того, что какой-то компонент системы начал работать некорректно, отчего Windows попросту не может нормально функционировать. Поэтому возникающие ошибки следует внимательно изучать и проводить их профилактику – без этого никто не может гарантировать ни стабильности работы системы, ни корректного сохранения ваших трудов.</p>

<p>Для начала необходимо просмотреть код ошибки, указанный на синем экране смерти. Если вы не успеваете его заметить (например, при загрузке системы она циклично перезагружается, на секунду показывая BSOD-ошибку), то необходимо отключить автоматическую перезагрузку системы при появлении ошибки. Для этого нужно выполнить два варианта:</p>

<p><strong><em>- При частично «живой» системе, если </em></strong><strong><em>Windows можно запустить.</em></strong> Нажмите правой клавишей мыши на <strong>Мой компьютер</strong>, выберите <strong>Свойства</strong>, в открывшемся окне перейдите по пункту <strong>Дополнительные параметры</strong>. Откроется окно, в котором необходимо выбрать вкладку <strong>Дополнительно</strong>, в которой в пункте <strong>Загрузка и восстановление</strong> нажмите на кнопку <strong>Параметры…</strong>. Откроется окошко <strong>Загрузка и восстановление</strong>, в котором в таблице <strong>Отказ системы</strong> нужно снять галочку с пункта <strong>Выполнить автоматическую перезагрузку</strong>, затем применить все действия нажатием кнопок <strong>ОК</strong>.</p>

<p><strong><em>- При неработающей </em></strong><strong><em>Windows, которая циклично перезагружается.</em></strong> После старта компьютера и прохождение теста BIOS сразу же нажмите на клавишу <strong>F8</strong>. Держите до появления окна с выбором пунктов аварийного запуска и выберите пункт <strong>Отключить автоматическую перезагрузку при отказе системы</strong>.</p>

<p style="text-align: center;"><img alt="ошибка 0хА" src="/upload/image/1bebdaca06bb.png" style="margin-top: 5px; margin-bottom: 5px; width: 600px; height: 367px;" title="ошибка 0хА" /></p>

<p>В любом из этих случаев вы должны были получить окно с пугающим набором цифр и букв. Впрочем, вся информация вам не нужна – смотрите в самом низу пункт Technical information, в котором вас должен интересовать набор цифр после слова <strong>«*** </strong><strong>STOP:»</strong> &nbsp;- именно он и заключает в себе код ошибки. Более подробную информацию можно получить чуть ниже – например, иногда в следующей строке указывается драйвер, который конфликтует с системой, или же другие данные. Впрочем, вам это не нужно – достаточно проверить, какой у вас тип ошибки. Рассмотрим более детально некоторые ошибки BSOD:</p>

<p><strong>- Ошибка БСОДа 0</strong><strong>x0000007</strong><strong>b</strong>. Такая ошибка чаще всего появляется на системах семейства Windows XP во время переноса системы с одного ПК на другой. Это конфликтуют драйвера дисковых устройств – система «привыкла» к одной конфигурации, а вместо этого ей нужно работать с другими устройствами.&nbsp; Для решения этой проблемы вам нужно загрузиться через любой Live CD с доступом к реестру вашей поврежденной системы и выключить в нем все ключи, относящиеся к дисковым контроллерам (или же, при наличии atapi.sys, pciidex.sys, pciide.sys и intelide.sys скопировать их в папку system32drivers вашей системы), перезагрузиться и получить рабочую систему.</p>

<p><strong>- </strong><strong>BSOD 0</strong><strong>x00000050.</strong> Эта ошибка появляется чаще всего во время подключения дефектного оборудования – планки памяти RAM или видеокарты (реже – системной службы).&nbsp; В этом случае отсоедините RAM-память или видеокарту от ПК и проверьте его работоспособность (не забывайте, что ПК нужна RAM-память, поэтому при необходимости поменяйте ее на рабочую планку, подходящую к вашей материнской плате). Если проблема исчезла – меняйте оборудование, если нет – проверьте систему на вирусы и поврежденные файлы.</p>

<p><strong>- </strong><strong>BSOD 0</strong><strong>x0000007</strong><strong>E</strong>. Это общая ошибка, и идентифицировать конкретное оборудование, службу или драйвер достаточно сложно – для этого необходимо провести комплекс мероприятий вроде очистки системного диска, замены/удаления видеокарты, очистки комплектующих драйверов и устранения проблем с кэшированием BIOS.</p>

<p><strong>- Ошибка БИОСа 501.</strong> Впрочем, вы можете увидеть и такое окно при запуске системы – это значит, что у вас некорректно работает контроллер материнской платы нижнего уровня BIOS. Чаще всего с такой проблемой сталкиваются владельцы ноутбуков Hewlett-Packard – и, если у вас возникла такая проблема, то вы можете либо попытаться восстановить BIOS, либо отнести его в сервисный центр. Последнее, безусловно, лучше, так как самостоятельно вы можете полностью потерять свой ноутбук, оставшись с кучей пластика на руках.</p>

<h3>&nbsp;Заработает ли компьютер после ошибки BSOD?</h3>

<p>Если вы уверены в своих знаниях, умениях и опыте – можете попробовать самостоятельно решить проблемы с возникшим «синим экраном смерти». Но, если вы недавно пользуетесь компьютером или же никогда не занимались восстановлением системы – лучшим решением вашей проблемы будет обращение в нашу компанию. Наши специалисты смогут в краткие сроки наладить работу вашего компьютера и обеспечить стабильную работу вашего устройства на долгие годы.</p>
