<p class='blog_title'>Почему USB так популярен?</p>
<p class='blog_date'>Автор: administrator</p>
<p class='blog_date1'>Дата: 2012-09-09</p>
<p class='blog_text'><h2 style="text-align:center"><span style="color:#173469"><strong><em>Немного истории</em></strong></span></h2>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">В 2000 году появилась на свет версия USB 2.0 уже столь популярного интерфейса передачи информации. </span></span><span style="font-family:times new roman,times,serif; font-size:18px">По сравнению с прошлой версией, то о</span><span style="font-size:18px"><span style="font-family:times new roman,times,serif">на увеличила пропускную способность более чем в 40 раз &nbsp;- до 480 Мбит/с в режиме высокой скорости. Очень хорошо было, что шина USB 2.0 была полностью совместима с USB 1.1.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Серийно, устройства USB 2.0 в таком виде, в котором мы их видим сегодня, вышли на рынок в 2002 году, когда был утвержден новый интерфейс. Пропускной способности хватало для внешних накопителей, телефонов (смартфонов) и цифровых камер, MP3-плееров, которым было необходимо передавать много данных. Контроллеру USB 2.0 удалось сильно потеснить конкурентов и полностью завоевать место на рынке, вытеснив последовательный и параллельный порты.&nbsp;</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Это нетрудно заметить, если взглянуть на современные материнские платы. Немногие из них все также имеют параллельный и последовательный порт. Они не требуются для периферии. Все функции передачи пакетов берет на себя USB.</span></span></p>

<h2 style="text-align:center"><em><span style="color:#173469"><strong>USB 3.0</strong></span></em></h2>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">В 2008 года USB Implementers Forum утвердил спецификации USB 3.0. </span></span><span style="font-family:times new roman,times,serif; font-size:18px">Повышение пропускной способности в&nbsp;</span><span style="font-size:18px"><span style="font-family:times new roman,times,serif">10 разе, &nbsp;по сравнению с USB 2.0. &nbsp;USB 3.0 поддерживает скорость передачи информации до 5 Гбит/с. Зачем так много?<img alt="usb 3.0" src="/upload/image/usb3.png" style="float:left; height:154px; margin-left:10px; margin-right:10px; width:200px" title="usb 3.0" /></span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Цифровые видеокамеры сейчас могут перезаписывать и сохранять гигабайты данных. Доля HD-видеокамер возрастает, и им требуются более быстрые и вместительные хранилища для обработки множества данных. </span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Используя на передачу нескольких десятков гигабайт USB 2.0 для монтажа потребуется значительное время. Implementers Forum утверждает, что пропускная способность останется важным параметром, и USB 3.0 хватит для всех потребительских устройств на протяжении ближайших пяти лет.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">USB 3.0 создан&nbsp;с учетом того, что он будет совместим с предыдущими версиями такого интерфейса. Поддерживая новый режим работы SuperSpeed (5 Гбит/с) он без проблем поддерживает и старые режимы:</span></span></p>

<ul>
	<li><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Low-Speed – скорость до 1,5 Мбит/с;</span></span></li>
	<li><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Full-Speed- скорость до 12 Мбит/с;</span></span></li>
	<li><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Hi-Speed - скорость до 480 Мбит/с .</span></span></li>
</ul>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Интерфейс SATA (eSATA) стал все более популярным и практически всегда встречается в компьютерах. Скорость передачи данных - 300 Мбайт/с, и при этом останется возможность горячего подключе</span></span><span style="font-size:18px"><span style="font-family:times new roman,times,serif">ния или встроенных линий питания. Однако eSATA все же уступает USB 3.0: у первого довольно жесткий и короткий кабель, и для него не существует хабов.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Да и нескоро, наверно</span></span><img alt="sata" src="/upload/image/sata.png" style="float:left; height:154px; margin-bottom:0px; margin-left:0px; margin-right:0px; margin-top:0px; width:200px" title="sata" /><span style="font-size:18px"><span style="font-family:times new roman,times,serif">е жёсткие диски приблизятся к уровню 600 Мбайт/с.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Еще одной альтернатива - это интерфейс FireWire 800. Он не способен составить вышеперечисленным интерфейсам конкуренцию: скорость больше чем 100 Мбайт/с нельзя обеспечить даже чисто технически, а устройств с этим разъемом сегодня на рынке гораздо меньше.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Кто использует в «медленные» периферийные устройства с (оргтехника, клавиатуры, веб-камеры, мыши), тем не так обязательно переходить тут же на USB 3.0. В этом случае их режим работы SuperSpeed не обеспечит никаких преимуществ. Но тем, кто часто работает с большими объемами информации, имеет смысл обратиться к новой версии USB.</span></span></p>

<hr />
<h2 style="text-align:center"><em><span style="color:#173469">А как же кабели?</span></em></h2>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Интерфейс USB 3.0 не подразумевает использование волоконной оптики, потому что она слишком дорога для массового рынка. Поэтому перед нами старый добрый медный кабель. Теперь у него правда уже 9 проводов, а не 4. Передача данных осуществляется по четырём из пяти дополнительных проводов в дифференциальном режиме. Одна пара проводов отвечает за передачу информации, другая - за прием. Принцип работы устройства схож с Serial ATA, при этом все устройства получают полную пропускную способность (в обоих направлениях). Пятый провод - "земля".</span></span></p>

<h2 style="text-align:center"><em><span style="color:#173469">Недостатки USB 2.0</span></em></h2>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Пропускная способность на максимуме у USB 2.0 около 480 Мбит/с, но на практике обеспечить такое не удастся (~33,5 Мбайт/с). Причина - В&nbsp;большие задержки шины USB между запросом на передачу данных и началом передачи. Шина FireWire, например, имея пропускную способность ниже, чем USB 2.0, в реальности обеспечивает пропускную способность для обмена данными больше.</span></span></p>

<p><span style="font-size:18px"><span style="font-family:times new roman,times,serif">Еще одним недостатком шины USB 2.0, является ненадежность крепления разъемов </span></span><span style="font-size:18px"><span style="font-family:times new roman,times,serif">на печатной плате. Поэтому, при высоких механических нагрузках, они могут отрываться вместе с печатными дорожками и площадками, Это чревато полной заменой платы – трудно надежно восстановить оторванные печатные дорожки. Этот минус наиболее часто проявляется в небольших устройствах - в телефонах или карманных цифровых проигрывателях.</span></span></p>

