<p class='blog_text'><h1 style="text-align:center"><strong>Почему монитор не включается?</strong></h1>

<p>То, что компьютер — вещь незаменимая, известно всем нам очень давно. Однако с ним зачастую могут происходить проблемы. Какие? Например, перестает работать монитор. Узнать причину, по которой это произошло, вот так вот просто порой невозможно, поскольку все звенья цепи, участвующие в отображении картинки на экране, запутаны между собой. Более того, далеко не всегда пропажа изображения говорит о неисправности в самом мониторе — вполне возможно, что это связано с проблемами в системе преобразования видеосигнала. В общем, вопрос этот далеко не самый простой. Тем не менее, сегодня мы попробуем помочь вам в решении этой трудности.</p>

<h3>Причины, по которым не работает монитор</h3>

<ul>
	<li>Не хотим показаться вам банальными, однако если при включении компьютера ваш монитор ничего не показывает, то в самую первую очередь необходимо проверить, вставлен ли шнур в розетку или сетевой фильтр. Если вставлен, обязательно проверьте, включена ли кнопка Power — вполне возможно, что кто-то из ваших родственников случайно нажал на нее, а вы просто забыли о ее существовании (на самом деле это очень распространенная ошибка).</li>
</ul>

<ul>
	<li>Если при включении и выключения монитора изображение на нем ничуть не меняется и не дает о себе знать, то проблема кроется, скорее всего, в данном устройстве. Самостоятельно починить вы его однозначно не сможете и потому единственное, что мы можем посоветовать вам сделать, так это проверить кабель питания на заведомо рабочем устройстве. На каком именно? Например, на системном блоке, ведь кабели у них совершенно идентичные. Для начала выключите системный блок (нажмите и удерживайте кнопку его выключения, пока он не перестанет шуметь). Затем с тыльной стороны выключите кнопку питания и переставьте кабели. После этого проделайте все в обратном порядке. Если системный блок заработал, значит теперь вы точно знаете, что не работает именно монитор, поэтому можно обращаться за помощью в сервисный центр или сдавать его по гарантии.</li>
</ul>

<ul>
	<li>Впрочем, подождите. Существует вероятность того, что настройки всех уровней убраны (яркость, контраст и так далее). Возможно, кто-то из друзей решил так пошутить над вами. Для этого необходимо самостоятельно изменить настройки через панель, которая находится на самом мониторе. Кстати, определить это просто — экран меняет свой цвет из черного на темно-серый. Уловить изменения трудно, при свете они практически не заметны, а вот в затемненной комнате — вполне.</li>
</ul>

<ul>
	<li>Если монитор включается, а вы видите сообщение об отсутствии сигнала, то есть вероятность того, что кабель, исходящий от самого устройства, попросту не воткнут в видеокарту. Обязательно вставьте его в слот.</li>
</ul>

<ul>
	<li>Теоретически возможно, что тот же самый кабель попросту не передает сигнал от видеокарты к экрану. Скорее всего, он просто поврежден, что неудивительно, если у вас имеются домашние животные в виде&nbsp;кошек или собак&nbsp;— они любят грызть провода. Если сам кабель в порядке, обязательно осмотрите штырьки в разъемах — они сделаны из мягкого металла и очень часто гнутся. Выравнивать их нужно предельно осторожно, поскольку существует вероятность сломать их и тогда единственным решением проблемы станет замена кабеля на новый.</li>
</ul>

<ul>
	<li>Если вы только приобрели компьютер и у вас в нем находятся сразу две видеокарты, возможно, что вы вставили штекер в другой разъем, поэтому его необходимо подключить к разъему другой видеокарты. Но почему тогда одна из них не работает? Скорее всего это связано с неправильными настройками БИОС, которые вы можете изменить самостоятельно (хотя заметим, что в таком случае желательно иметь хотя бы небольшой опыт в подобных настройках).</li>
</ul>

<ul>
	<li>Изображения нет потому, что не работает видеокарта. Тоже довольно-таки распространенное явление. Как узнать, что проблема именно в этом устройстве? Во-первых, ваш компьютер обязательно расскажет вам об этом серией звуковых сигналов (об их последовательности можно узнать в мануале, который идет вместе с материнской картой). Во-вторых, ее можно вставить в другой системный блок, если такая возможность присутствует. Правда, далеко не все видеокарты подходят к различным материнским платам.</li>
</ul>

<ul>
	<li>Зачастую подобное может произойти и в том случае, если материнская плата приказала долго жить или она просто неисправна. В этом случае вы вообще не услышите никаких звуков (один сигнал при включении системного блока подается всегда, если самодиагностика завершена успешно). Стоит также помнить, что в случае неисправности этого устройства компьютер продолжает работать в привычном для него режиме — то есть включается, шумит, но не загружается, изображение отсутствует.</li>
</ul>

<ul>
	<li>Тоже самое происходит тогда, когда присутствуют неисправности в процессоре. Однако в этом случае БИОС подает сигнал, символизирующий о неполадках в процессоре.</li>
</ul>

<h3>Что делать?</h3>

<p>О возможности устранения причин неполадок мы написали выше. Если говорить о более серьезном ремонте, то большинству пользователей это не под силу, а потому единственный вариант решения этого вопроса — обращение в сервисный центр. Однако это не всегда имеет смысл, поскольку стоимость нового&nbsp;монитора&nbsp;может быть даже ниже, чем ремонт старого. Но это решать, конечно же, только вам.</p>

